const TOKEN_PATTERN = /[a-z0-9]+/g;

export function queryHasNounOrVerb(query: string): boolean {
  const tokens = query.toLowerCase().match(TOKEN_PATTERN);
  if (!tokens) {
    return false;
  }
  return tokens.some((token) => !FUNCTION_WORDS.has(token));
}
